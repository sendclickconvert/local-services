// ─── HELPER FUNCTIONS ─────────────────────────────────────

export function getCounty(slug: string): County | undefined {
  return counties.find(c => c.slug === slug);
}

export function getTown(countySlug: string, townSlug: string): Town | undefined {
  const county = getCounty(countySlug);
  return county?.towns.find(t => t.slug === townSlug);
}

export function getNeighbors(countySlug: string): County[] {
  const county = getCounty(countySlug);
  if (!county) return [];
  return county.neighbors
    .map(slug => getCounty(slug))
    .filter((c): c is County => c !== undefined);
}

export function getAllTowns(): Array<{ county: County; town: Town }> {
  return counties.flatMap(county =>
    county.towns.map(town => ({ county, town }))
  );
}

export const primaryCounties = counties.filter(c => c.tier === 'primary');
export const secondaryCounties = counties.filter(c => c.tier === 'secondary');
